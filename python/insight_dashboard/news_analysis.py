def event_kind(title: str) -> str:
    if "解读" in title:
        return "解读"
    if re.search(r"\d+(?:\.\d+)?%|指数|数据|利润|增速|增长|下降|变动情况|监测", title):
        return "数据"
    if any(word in title for word in ("价格调整", "调价", "价格")):
        return "价格"
    if any(word in title for word in ("会议", "座谈", "会谈", "发布会", "论坛")):
        return "会议"
    if any(word in title for word in ("意见", "通知", "办法", "条例", "方案", "规划", "细则")):
        return "政策"
    return "信息"


